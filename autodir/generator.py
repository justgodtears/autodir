from pathlib import Path
from autodir.naming import PathEntry


def build_path_expression(path_from_root: Path) -> str:
    """
    Zamienia względną ścieżkę (np. Path("data/ad.csv")) na fragment
    kodu Python budujący tę ścieżkę względem ROOT, np.:
    'ROOT / "data" / "ad.csv"'
    """
    quoted_parts = []
    parts = path_from_root.parts
    for part in parts:
        quoted_parts.append(f'"{part}"')

    joined = " / ".join(quoted_parts)
    return "ROOT / " + joined


def build_entry_line(entry: PathEntry) -> str:
    """
    Buduje jedną linijkę kodu dla wygenerowanego pliku, np.:
    'AD_CSV = ROOT / "data" / "ad.csv"  # source: data/ad.csv'
    """
    expression = build_path_expression(entry.path_from_root)
    comment = f"# source: {entry.path_from_root.as_posix()}"
    return f"{entry.name} = {expression}  {comment}"


def build_file_content(entries: list[PathEntry]) -> str:
    """
    Buduje pełną zawartość wygenerowanego pliku .py z listy PathEntry.
    """
    header = (
        "# This file is auto-generated by autodir. Do not edit manually.\n"
        "from pathlib import Path\n"
        "\n"
        "ROOT = Path(__file__).parent\n"
    )
    list_str = []
    for entry in entries:
        list_str.append(build_entry_line(entry))

    one_str = "\n".join(list_str)
    whole_file = header + "\n" + one_str + "\n"
    return whole_file

